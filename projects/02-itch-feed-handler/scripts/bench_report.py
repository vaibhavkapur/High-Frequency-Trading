#!/usr/bin/env python3
"""Render bench.jsonl (from scripts/run_benchmarks.sh) as Markdown tables.

Every number in the output is read from the raw results file; nothing is
computed here beyond unit conversion and ratios between rows.
"""
import json
import sys

MODE_ORDER = ["frame", "decode", "book-flat", "book-std"]
MODE_NAME = {
    "frame": "framing only",
    "decode": "framing + decode",
    "book-flat": "decode + book (flat index)",
    "book-std": "decode + book (unordered_map)",
}


def main():
    rows = [json.loads(line) for line in open(sys.argv[1]) if line.strip()]
    env = open(sys.argv[2]).read() if len(sys.argv) > 2 else ""
    profiles = []
    for r in rows:
        if r["label"] not in profiles:
            profiles.append(r["label"])
    by = {(r["label"], r["mode"]): r for r in rows}

    print("# Benchmark results\n")
    print("Generated by `scripts/run_benchmarks.sh` from `bench.jsonl` in this directory.")
    print("Methodology and caveats: `docs/benchmarks.md`.\n")
    if env:
        print("## Environment\n\n```text\n%s```\n" % env)

    print("## Throughput (median of timed passes)\n")
    print(
        "`ns/msg` is the median pass; min and max show the spread across passes, "
        "which is the honest error bar for each row.\n"
    )
    print("| Profile | Stage | Messages | M msgs/s | MB/s | ns/msg | min | max |")
    print("|---|---|---:|---:|---:|---:|---:|---:|")
    for p in profiles:
        for m in MODE_ORDER:
            r = by.get((p, m))
            if r:
                print(
                    "| %s | %s | %d | %.1f | %.0f | %.1f | %.1f | %.1f |"
                    % (
                        p,
                        MODE_NAME[m],
                        r["messages"],
                        r["median_msgs_per_sec"] / 1e6,
                        r["median_mb_per_sec"],
                        r["median_ns_per_msg"],
                        r["min_ns_per_msg"],
                        r["max_ns_per_msg"],
                    )
                )

    print("\n## Per-message latency (separate instrumented pass)\n")
    any_row = next((r for r in rows if "latency_ns" in r), None)
    if any_row:
        print(
            "Timer: smallest non-zero `steady_clock` step %d ns, back-to-back read pair "
            "%d ns. Values at or below these are at the timer's floor, and every sample "
            "includes the cost of the two clock reads.\n"
            % (any_row["clock_min_nonzero_ns"], any_row["clock_read_pair_ns"])
        )
    print("| Profile | Stage | p50 ns | p99 ns | p99.9 ns | max ns |")
    print("|---|---|---:|---:|---:|---:|")
    for p in profiles:
        for m in MODE_ORDER[1:]:
            r = by.get((p, m))
            if r and "latency_ns" in r:
                l = r["latency_ns"]
                print(
                    "| %s | %s | %d | %d | %d | %d |"
                    % (p, MODE_NAME[m], l["p50"], l["p99"], l["p999"], l["max"])
                )

    print("\n## Memory and allocations\n")
    print(
        "Peak RSS includes the resident pages of the memory-mapped input file "
        "(size shown) and is sampled after the warm-up pass.\n"
    )
    print(
        "| Profile | Stage | Live orders at end | Allocations (cold pass) "
        "| Allocs / M msgs | Peak RSS MB | Input MB |"
    )
    print("|---|---|---:|---:|---:|---:|---:|")
    for p in profiles:
        for m in MODE_ORDER:
            r = by.get((p, m))
            if r:
                print(
                    "| %s | %s | %d | %d | %.1f | %.0f | %.0f |"
                    % (
                        p,
                        MODE_NAME[m],
                        r["live_orders_at_end"],
                        r["cold_pass_allocations"],
                        r["allocations_per_million_msgs"],
                        r["peak_rss_bytes_after_warmup"] / 1e6,
                        r["file_bytes"] / 1e6,
                    )
                )

    print("\n## Measured trade-off: order index implementation\n")
    print("Ratios use the median pass; the min-pass ratio is shown as a cross-check.\n")
    print(
        "| Profile | flat ns/msg | unordered_map ns/msg | ratio (median) | ratio (min) "
        "| allocs/M flat | allocs/M map |"
    )
    print("|---|---:|---:|---:|---:|---:|---:|")
    for p in profiles:
        a, b = by.get((p, "book-flat")), by.get((p, "book-std"))
        if a and b:
            print(
                "| %s | %.1f | %.1f | %.2fx | %.2fx | %.1f | %.1f |"
                % (
                    p,
                    a["median_ns_per_msg"],
                    b["median_ns_per_msg"],
                    b["median_ns_per_msg"] / a["median_ns_per_msg"],
                    b["min_ns_per_msg"] / a["min_ns_per_msg"],
                    a["allocations_per_million_msgs"],
                    b["allocations_per_million_msgs"],
                )
            )
        if a and b and a["checksum"] != b["checksum"]:
            print("\n**WARNING: book digests differ between index implementations for %s.**" % p)

    r = rows[0]
    print(
        "\nCompiler: `%s`  \nFlags: `%s`  \nThread scheduling: `%s`"
        % (r["compiler"], r["flags"], r.get("scheduling", "default"))
    )


if __name__ == "__main__":
    main()
